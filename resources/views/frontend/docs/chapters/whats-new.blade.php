  <div class="doc-sec" id="profit-cogs">
    <h3>How COGS Is Calculated</h3>
    <p>Cost of Goods Sold (COGS) is recorded <em>at the moment of checkout</em>, not retrospectively. When a cashier completes a sale, the system looks up the stock layer cost for each item and stores it in the sale record. This means:</p>
    <ul>
      <li>Changing a product's cost after a sale has no effect on past COGS figures.</li>
      <li>Products added to stock via Goods Receive Notes carry their GRN unit cost into the calculation.</li>
      <li>If stock layer cost is not available (e.g. service items with no stock), that item contributes zero to COGS and its full selling price becomes gross profit.</li>
    </ul>

    <div class="callout note">
      <div class="callout-icon"><i class="fa-solid fa-circle-info"></i></div>
      <div class="callout-body"><strong>Note</strong> Returns are tracked separately and excluded from the revenue and COGS totals shown in the Profit Report. The <em>Returns</em> amount is calculated but not currently displayed as a standalone KPI card.</div>
    </div>
