<div class="doc-sec">
  <h3 id="financial-overview-cash-flow">Financial Overview — Cash Flow</h3>
  <p>Click the <span class="tab-label">FINANCE</span> tab to open the finance panel. The default view is <strong>Cash Flow</strong>, showing:</p>
  <ul>
    <li>Monthly income vs. expenses chart</li>
    <li>Running account balances</li>
    <li>Recent income and expense transactions</li>
    <li>Net cash position for the current period</li>
  </ul>
  <p>Use the date range selector to zoom into any period or compare months.</p>
</div>

<div class="doc-sec">
  <h3 id="bank-accounts">Bank Accounts</h3>
  <p>All payments flow through accounts. Go to the Finance panel and click <span class="ui">Accounts</span> in the sub-navigation. Here you can:</p>
  <ul>
    <li>Add bank accounts, cash tills, and mobile money wallets</li>
    <li>View the full transaction ledger for each account</li>
    <li>Transfer money between accounts</li>
    <li>Reconcile account balances with your bank statement</li>
  </ul>
  <div class="callout note">
    <div class="callout-icon"><i class="fa-solid fa-circle-info"></i></div>
    <div class="callout-body">
      <strong>Note</strong>
      You must add at least one bank account before you can process sales. The Bank Account Setup Wizard runs automatically on first login.
    </div>
  </div>
</div>

<div class="doc-sec">
  <h3 id="bill-management">Bill Management</h3>
  <p>Record supplier invoices and bills you need to pay. In the Finance ribbon, click <span class="ui">New Bill</span>.</p>
  <div class="doc-steps">
    <div class="doc-step">
      <div class="step-num">1</div>
      <div class="step-body">
        <strong>Enter bill details</strong>
        <p>Select the supplier, enter the invoice number, date, and due date. Add line items for each expense category.</p>
      </div>
    </div>
    <div class="doc-step">
      <div class="step-num">2</div>
      <div class="step-body">
        <strong>Record payment</strong>
        <p>When you pay the bill, open it and click <span class="ui">Record Payment</span>. Select the account the payment was made from and the amount paid.</p>
      </div>
    </div>
    <div class="doc-step">
      <div class="step-num">3</div>
      <div class="step-body">
        <strong>Track partial payments</strong>
        <p>You can make multiple partial payments against one bill. The outstanding balance updates after each payment until the bill is fully settled.</p>
      </div>
    </div>
  </div>
</div>

<div class="doc-sec">
  <h3 id="loans">Loans</h3>
  <p>Track business loans — both money borrowed and money lent. From the Finance panel sub-navigation, click <strong>Loans</strong>. Record the principal amount, interest rate, and repayment schedule. The system tracks each repayment and shows the remaining balance.</p>
</div>

<div class="doc-sec">
  <h3 id="rentals-properties">Rentals &amp; Properties</h3>
  <p>If your business manages rental properties or pays rent, the <strong>Rentals</strong> and <strong>Properties</strong> views let you track lease terms, monthly payments, and property-related expenses. Each property links to a billing schedule that reminds you of upcoming payments.</p>
</div>

<div class="doc-sec">
  <h3 id="finance-reports">Finance Reports</h3>
  <p>Access standard financial reports from the <strong>Reports</strong> ribbon group:</p>
  <ul>
    <li><strong>Profit &amp; Loss</strong> — income vs. expenses for any period</li>
    <li><strong>Account Statement</strong> — full ledger for a specific account</li>
    <li><strong>Expense Summary</strong> — breakdown of spending by category</li>
  </ul>
</div>
