<div class="doc-sec">
  <h3 id="adding-employees">Adding Employees</h3>
  <div class="doc-steps">
    <div class="doc-step">
      <div class="step-num">1</div>
      <div class="step-body">
        <strong>Click New Employee</strong>
        <p>In the <span class="tab-label">HR</span> ribbon, click <span class="ui">New Employee</span> in the People group.</p>
      </div>
    </div>
    <div class="doc-step">
      <div class="step-num">2</div>
      <div class="step-body">
        <strong>Overview tab — Basic information</strong>
        <p>Enter the employee's name, job title, email, phone, and start date. Assign them to a department and set their employment type (Full-time, Part-time, or Contract).</p>
      </div>
    </div>
    <div class="doc-step">
      <div class="step-num">3</div>
      <div class="step-body">
        <strong>Personal tab — Identity details</strong>
        <p>Add the national ID number, date of birth, address, and emergency contact information.</p>
      </div>
    </div>
    <div class="doc-step">
      <div class="step-num">4</div>
      <div class="step-body">
        <strong>Save the record</strong>
        <p>Click <span class="ui">Save Employee</span>. The employee now appears in your team roster and can be included in payroll runs.</p>
      </div>
    </div>
  </div>
</div>

<div class="doc-sec">
  <h3 id="departments">Departments</h3>
  <p>Click <span class="ui">Departments</span> in the HR ribbon to create and manage departments. Each department can have:</p>
  <ul>
    <li>A department head employee</li>
    <li>A list of assigned employees</li>
    <li>A salary sheet tab showing all members' compensation</li>
  </ul>
</div>

<div class="doc-sec">
  <h3 id="salary-payroll">Salary &amp; Payroll</h3>
  <p>From the <strong>Compensation</strong> ribbon group, manage salaries and run payroll:</p>
  <div class="doc-steps">
    <div class="doc-step">
      <div class="step-num">1</div>
      <div class="step-body">
        <strong>Set salary for each employee</strong>
        <p>Open an employee record and go to the salary section. Enter their base salary and any allowances.</p>
      </div>
    </div>
    <div class="doc-step">
      <div class="step-num">2</div>
      <div class="step-body">
        <strong>Run payroll</strong>
        <p>Click <span class="ui">Payroll Run</span>. Select the pay period (monthly, bi-weekly), choose the employees to include, and confirm the amounts. The payroll is recorded as an expense against the business account you select.</p>
      </div>
    </div>
    <div class="doc-step">
      <div class="step-num">3</div>
      <div class="step-body">
        <strong>Print payslips</strong>
        <p>After confirming, generate and print individual payslips for each employee from the payroll run summary screen.</p>
      </div>
    </div>
  </div>
</div>

<div class="doc-sec">
  <h3 id="attendance">Attendance</h3>
  <p>Track attendance directly in the app. Open an employee record and use the attendance log to record daily check-in and check-out times, late arrivals, absences, and leave. Attendance data feeds into payroll calculations automatically when configured.</p>
</div>
