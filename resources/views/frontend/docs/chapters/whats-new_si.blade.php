    <p>විකුණුම් පිරිවැය (COGS) සටහන් වන්නේ පසුව නොව, <em>ගෙවීම සිදුවන මොහොතේදීමය</em>. මුදල් අයකරු විකිණීමක් සම්පූර්ණ කළ විට, පද්ධතිය සෑම අයිතමයකම තොග ස්තර පිරිවැය සොයා විකුණුම් වාර්තාවේ සුරකියි. එයින් අදහස් වන්නේ:</p>
